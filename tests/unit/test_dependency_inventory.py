@pytest.mark.parametrize(("fname", "content", "eco", "needle"), MALFORMED)
def test_malformed_manifest_is_a_per_file_error(tmp_path, fname, content, eco, needle):
    (tmp_path / "sub").mkdir()
    (tmp_path / "sub" / fname).write_text(content)
    # a well-formed sibling manifest is still listed
    (tmp_path / "requirements.txt").write_text("flask==3.0\n")
    (tmp_path / "Cargo.toml").write_text('[dependencies]\nserde = "1"\n')
    ecos, errors = build_inventory(tmp_path, {eco})
    assert len(errors) == 1 and errors[0].startswith(f"sub/{fname}"), errors
    assert needle in errors[0]
    direct = {d.name for d in ecos[0].direct}
    assert direct == ({"flask"} if eco == "pypi" else {"serde"})


def test_oversized_manifest_is_refused_before_parsing(tmp_path):
    """Just over the cap is a per-file error; exactly at the cap still parses."""
    from services.dependency_extraction import MAX_MANIFEST_CHARS

    def padded(text: str, size: int) -> str:
        return text + "#" * (size - len(text) - 1) + "\n"

    over, at = tmp_path / "over", tmp_path / "at"
    for root, size in ((over, MAX_MANIFEST_CHARS + 1), (at, MAX_MANIFEST_CHARS)):
        root.mkdir()
        (root / "pyproject.toml").write_text(padded('[project]\ndependencies = ["a"]\n', size))
        (root / "requirements.txt").write_text(padded("b==1\n", size))

    _, errors = build_inventory(over, {"pypi"})
    assert sorted(e.split(":")[0] for e in errors) == ["pyproject.toml", "requirements.txt"]
    assert all(f"exceeds {MAX_MANIFEST_CHARS} characters" in e for e in errors)
    ecos, errors = build_inventory(at, {"pypi"})
    assert errors == []
    assert {d.name for d in ecos[0].direct} == {"a", "b"}


def test_well_formed_manifests_produce_no_errors(tmp_path):
    """Negative control: the shapes the checks accept are the real formats."""
    (tmp_path / "pyproject.toml").write_text(
        "[project]\ndependencies = []\n[project.optional-dependencies]\nx = []\n"
        '[dependency-groups]\ndev = [{include-group = "lint"}]\nlint = ["ruff"]\n'
        "[tool.uv]\ndev-dependencies = []\n"
    )
    (tmp_path / "Cargo.toml").write_text(
        '[package]\nname = "a"\n[workspace]\nmembers = []\n'
        "[target.'cfg(unix)'.dependencies]\nlibc = \"0.2\"\n"
    )
    ecos, errors = build_inventory(tmp_path, {"pypi", "crates.io"})
    assert errors == []
    assert {d.name for e in ecos for d in e.direct} == {"ruff", "libc"}


def test_conflicted_cargo_lock_is_still_scanned(tmp_path):
    """A real `git merge` conflict in Cargo.lock: not TOML, but its crates are read.

    Reading it as no packages would report the repo clean.
    """
    import os
    import subprocess

    from services.dependency_extraction import DependencyExtractor

    repo = tmp_path / "repo"
    shutil.copytree(FIXTURES / "cargo" / "vulnproj", repo)
    lock = repo / "Cargo.lock"
    original = lock.read_text()

    # Inside a git hook (pre-push runs this suite) GIT_DIR / GIT_INDEX_FILE point
    # at the repo being pushed; without dropping them these commands would run
    # against it instead of the tmp repo.
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}

    def git(*args: str) -> None:
        subprocess.run(
            ["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],
            cwd=repo,
            env=env,
            check=True,
            capture_output=True,
        )

    git("init", "-q", "-b", "main")
    git("add", "-A")
    git("commit", "-qm", "base")
    git("checkout", "-qb", "other")
    lock.write_text(original.replace('version = "1.1.0"', 'version = "1.1.1"'))
    git("commit", "-qam", "other")
    git("checkout", "-q", "main")
    lock.write_text(original.replace('version = "1.1.0"', 'version = "1.1.2"'))
    git("commit", "-qam", "main")
    try:
        git("merge", "-q", "other")
    except subprocess.CalledProcessError:
        pass  # the conflict is the point
    assert "<<<<<<<" in lock.read_text()  # a real conflict

    found = {(p.name, p.version) for p in DependencyExtractor().extract_dependencies(repo)}
    assert ("smallvec", "1.6.0") in found and ("smallvec", "0.6.14") in found


