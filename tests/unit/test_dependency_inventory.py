    ("Cargo.toml", 'target = {a = "x"}\n', "crates.io", "[target.a] is not a table"),
    ("Cargo.toml", _DEEP_TOML, "crates.io", "not valid TOML"),
    ("Cargo.lock", "package = 5\n", "crates.io", "not an array of tables"),
    ("Cargo.lock", _DEEP_TOML, "crates.io", "not valid TOML"),
