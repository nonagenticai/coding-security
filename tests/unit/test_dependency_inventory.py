"""POST /api/security/sbom/{name}/dependencies: per-repo direct + resolved, PyPI + crates.

Workspace layout used here (a py2rust workspace): the primary repo is the Rust
target (tests/fixtures/cargo/vulnproj, Cargo.lock generated by cargo, see its
generate.sh), the Python source sits at .repos/o__src (tests/fixtures/pyproj,
uv.lock generated by uv, see its generate.sh).

The advisory DB is not exercised against real records here: the baked offline
OSV DB exists only in the image, and the image build asserts RUSTSEC-2021-0003
is in its crates.io/smallvec.json (Dockerfile, `grep -q RUSTSEC-2021-0003`).
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from services.dependency_inventory import build_inventory

from .workspace_server import WorkspaceServer

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"


def _workspace(root: Path) -> Path:
    shutil.copytree(FIXTURES / "cargo" / "vulnproj", root)
    shutil.copytree(FIXTURES / "pyproj", root / ".repos" / "o__src")
    return root


# ── unit: the parser ────────────────────────────────────────────────────────


def test_inventory_crates_direct_and_resolved(tmp_path):
    ws = _workspace(tmp_path / "ws")
    ecos, errors = build_inventory(ws, {"pypi", "crates.io"})
    assert errors == []
    assert [e.ecosystem for e in ecos] == ["crates.io"]  # .repos/ excluded from primary
    crates = ecos[0]
    assert crates.manifest_files == ["Cargo.toml", "time/Cargo.toml"]
    assert crates.lock_files == ["Cargo.lock"]
    assert {(d.name, d.specifier, d.dev) for d in crates.direct} == {
        ("smallvec", "=1.6.0", False),
        ("unicode-normalization", "=0.1.8", False),
        ("time", "path = time", False),
        ("static_assertions", "1", True),
    }
    # The path crate `time` (no registry source) is not a resolved dependency; of
    # the two smallvecs only the one the root crate depends on is direct.
    assert {(r.name, r.version, r.direct, r.dev) for r in crates.resolved} == {
        ("maybe-uninit", "2.0.0", False, False),
        ("smallvec", "0.6.14", False, False),
        ("smallvec", "1.6.0", True, False),
        ("static_assertions", "1.1.0", True, True),
        ("unicode-normalization", "0.1.8", True, False),
    }
    purls = {r.purl for r in crates.resolved}
    assert "pkg:cargo/smallvec@1.6.0" in purls


def test_inventory_pypi_direct_dev_and_transitive(tmp_path):
    ws = _workspace(tmp_path / "ws")
    ecos, errors = build_inventory(ws / ".repos" / "o__src", {"pypi", "crates.io"})
    assert errors == []
    assert [e.ecosystem for e in ecos] == ["pypi"]
    pypi = ecos[0]
    assert {(d.name, d.specifier, d.dev) for d in pypi.direct} == {
        ("python-dateutil", ">=2.8", False),
        ("six", "@ git+https://github.com/benjaminp/six@1.17.0", False),
        ("iniconfig", ">=2", True),
        ("ruff", "==0.6.0", True),
        ("tzdata", "==2024.1", True),
    }
    resolved = {r.name: (r.direct, r.dev) for r in pypi.resolved}
    assert resolved == {
        "python-dateutil": (True, False),
        "iniconfig": (True, True),
        # declared (requirements-dev.txt pins 2024.1) but the lock resolves another
        # version: that version is not the declared one, so it is transitive
        "tzdata": (False, False),
    }
    # neither the project itself (virtual) nor the git-sourced six is a PyPI package
    assert not {"pyproj", "six"} & set(resolved)


