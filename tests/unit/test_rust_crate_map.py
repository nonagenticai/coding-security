"""rust_crate_map: the REAL map file's invariants, and the map built from a real repo.

The repo is tests/fixtures/pyproj (uv.lock generated by the real uv, see its
generate.sh): one dep the map knows with a locked version (python-dateutil),
std/toolchain deps with an empty crate list (six, ruff), one whose lockfile
version is not the declared one (tzdata) and one the map does not know
(iniconfig).
"""

from __future__ import annotations

import tomllib
from pathlib import Path

import pytest

from services.dependency_inventory import _norm_pypi, build_inventory
from services.rust_crate_map import MAP_PATH, load_crate_map, parse_crate_map, rust_crate_map

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"


def test_real_map_file_holds_its_invariants():
    crate_map = load_crate_map()  # parse_crate_map raises on any violation
    assert crate_map.version
    raw = tomllib.loads(MAP_PATH.read_text(encoding="utf-8"))["packages"]
    assert len(crate_map.packages) == len(raw) >= 40
    assert all(key == _norm_pypi(key) for key in crate_map.packages)
    assert crate_map.packages["fastapi"].crates == ("axum",)
    assert crate_map.packages["pydantic"].crates == ("serde", "validator")


def test_map_file_lives_under_src_so_the_image_ships_it():
    # The Dockerfile copies src/ into the image and .dockerignore does not exclude it.
    src = Path(__file__).resolve().parents[2] / "src"
    assert MAP_PATH.is_relative_to(src)
    assert "COPY --chown=appuser:appuser src/ ./src/" in (src.parent / "Dockerfile").read_text()


@pytest.mark.parametrize(
    ("text", "error"),
    [
        ('[packages.x]\ncrates = ["a"]\n', "map_version"),
        ('map_version = "1"\n[packages.Py_YAML]\ncrates = ["serde_yaml"]\n', "normalised"),
        ('map_version = "1"\n[packages.six]\ncrates = []\n', "needs a note"),
        ('map_version = "1"\n[packages.x]\ncrates = "a"\n', "list of crate names"),
        ('map_version = "1"\n[packages.x]\ncrates = []\ntools = [""]\n', "tools is not a list"),
        ('map_version = "1"\n[packages.x]\ncrates = ["a"]\nkind = "dev"\n', "only `crates`"),
    ],
)
def test_parse_rejects_each_violation(text, error):
    """Negative controls: the invariant test above would pass vacuously without these."""
    with pytest.raises(ValueError, match=error):
        parse_crate_map(text)


def test_parse_rejects_a_duplicate_key():
    with pytest.raises(tomllib.TOMLDecodeError):
        parse_crate_map('map_version = "1"\n[packages.x]\ncrates = []\n[packages.x]\ncrates = []\n')


def test_crate_map_of_a_real_repo():
    ecos, errors = build_inventory(FIXTURES / "pyproj", {"pypi"})
    assert errors == []
    result = rust_crate_map(ecos)
    assert result is not None
    assert result.map_version == load_crate_map().version
    assert [m.model_dump() for m in result.mapped] == [
        {
            "pypi": "python-dateutil",
            "version": "3.0.0",
            "dev": False,
            "crates": ["chrono"],
            "tools": [],
            "note": None,
        },
        {
            "pypi": "ruff",
            "version": None,  # not in uv.lock (requirements-dev.txt only)
            "dev": True,
            "crates": [],
            "tools": [],
            "note": "toolchain: cargo clippy + rustfmt",
        },
        {
            "pypi": "six",
            "version": None,  # a git source: not a locked PyPI package
            "dev": False,
            "crates": [],
            "tools": [],
            "note": "Python 2/3 compatibility shim: nothing to port",
        },
        {
            "pypi": "tzdata",
            "version": None,  # the lock resolves 2026.6, not the declared 2024.1
            "dev": True,
            "crates": ["chrono-tz"],
            "tools": [],
            "note": None,
        },
    ]
    assert result.unmapped == ["iniconfig"]


def test_crate_map_is_null_without_a_pypi_ecosystem():
    ecos, _ = build_inventory(FIXTURES / "cargo" / "vulnproj", {"pypi", "crates.io"})
    assert [e.ecosystem for e in ecos] == ["crates.io"]
    assert rust_crate_map(ecos) is None


def test_crate_map_normalises_declared_and_locked_names(tmp_path):
    """Manifest + lock spell names unnormalised; lookup and version join still hit.

    Dropping normalisation on either lookup sends these to `unmapped` / version null.
    """
    (tmp_path / "requirements.txt").write_text(
        "PyYAML>=6\ntyping_extensions>=4\nPython.Dateutil>=2.8\n"
    )
    (tmp_path / "poetry.lock").write_text(
        '[[package]]\nname = "PyYAML"\nversion = "6.0.2"\n\n'
        '[[package]]\nname = "typing_extensions"\nversion = "4.12.2"\n\n'
        '[[package]]\nname = "python-dateutil"\nversion = "2.9.0"\n'
    )
    ecos, errors = build_inventory(tmp_path, {"pypi"})
    assert errors == []
    result = rust_crate_map(ecos)
    assert result is not None
    assert result.unmapped == []
    assert {m.pypi: (m.version, m.crates) for m in result.mapped} == {
        "python-dateutil": ("2.9.0", ["chrono"]),
        "pyyaml": ("6.0.2", ["serde_yaml"]),
        "typing-extensions": ("4.12.2", []),
    }


def test_install_only_tools_are_not_crates(tmp_path):
    """cargo-nextest / cargo-llvm-cov / cargo-audit are `cargo install` binaries, not deps."""
    (tmp_path / "requirements-dev.txt").write_text("pytest>=8\npytest-cov>=5\npip-audit>=2\n")
    ecos, _ = build_inventory(tmp_path, {"pypi"})
    result = rust_crate_map(ecos)
    assert result is not None
    assert {m.pypi: (m.crates, m.tools, m.dev) for m in result.mapped} == {
        "pip-audit": ([], ["cargo-audit"], True),
        "pytest": ([], ["cargo-nextest"], True),
        "pytest-cov": ([], ["cargo-llvm-cov"], True),
    }
    packages = load_crate_map().packages
    tools = {t for entry in packages.values() for t in entry.tools}
    crates = {c for entry in packages.values() for c in entry.crates}
    assert not {c for c in crates if c.startswith("cargo-")}  # every cargo-* binary is a tool
    assert tools == {"cargo-nextest", "cargo-llvm-cov", "cargo-audit"}
