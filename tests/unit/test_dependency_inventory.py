@pytest.fixture
def call(test_client, tenant_headers, tmp_path, monkeypatch):
    """POST the route for a LOCAL workspace dir: the workspace record comes from
    the real local coding-containers stand-in (tests/unit/workspace_server.py)."""
    from config.settings import get_settings

    db = tmp_path / "osv-db"  # an offline DB with a crates.io dir and no records
    (db / "crates.io").mkdir(parents=True)

    def _call(ws: Path, params: dict | None = None):
        with WorkspaceServer(ws, codebase_path=str(ws)) as server:
            monkeypatch.setenv("CONTAINERS_SERVICE_URL", server.url)
            monkeypatch.setenv("OSV_OFFLINE_DB_DIR", str(db))
            get_settings.cache_clear()
            return test_client.post(
                "/api/security/sbom/ws/dependencies", params=params or {}, headers=tenant_headers
            )

    return _call


def test_route_lists_every_repo(call, tmp_path):
    resp = call(_workspace(tmp_path / "ws"))
    assert resp.status_code == 200, resp.text
    body = resp.json()
    repos = {r["repo"]: r for r in body["result"]["repos"]}
    assert list(repos) == ["primary", ".repos/o__src"]

    crates = repos["primary"]["ecosystems"][0]
    # crates.io DB present: every crate is CHECKED (no record -> no advisories)
    assert all(r["advisories_checked"] and r["advisories"] == [] for r in crates["resolved"])

    pypi = repos[".repos/o__src"]["ecosystems"][0]
    # no PyPI dir in the DB -> PyPI entries are UNCHECKED, and the response says
    # so (degraded), instead of reading as clean
    assert all(r["advisories_checked"] is False for r in pypi["resolved"])
    assert body["status"] == "degraded"
    assert any("pypi" in e for e in body["result"]["advisory_lookup_errors"])

    # direct PyPI deps -> Rust crates; the crates-only primary repo has no map
    assert repos["primary"]["rust_crate_map"] is None
    crate_map = repos[".repos/o__src"]["rust_crate_map"]
    assert {m["pypi"]: m["crates"] for m in crate_map["mapped"]} == {
        "python-dateutil": ["chrono"],
        "ruff": [],
        "six": [],
        "tzdata": ["chrono-tz"],
    }
    assert crate_map["unmapped"] == ["iniconfig"]
    assert crate_map["map_version"]


